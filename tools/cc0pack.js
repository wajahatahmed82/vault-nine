// Packs the processed CC0 textures into src/cc0data.js (base64 data URLs), so
// the single-file build and the dev server load the same thing.
//
// Pipeline (see ASSETS.md for sources and licences):
//   1. Download the ambientCG 1K-JPG zips; extract *_Color, *_NormalGL and
//      *_Roughness into shots/cc0in/.
//   2. In the browser (dev server + tools/shotsrv.js), draw each map to a
//      512 px canvas -- Plaster001 and WoodSiding008 colour maps are converted
//      to light neutral grey so the town's paint colours can tint them -- and
//      POST the JPEGs to shotsrv as shots/cc0_<Asset>_<Map>.jpg.
//   3. node tools/cc0pack.js
const fs = require('fs');
const path = require('path');

const ASSETS = ['Bricks104', 'Plaster001', 'WoodSiding008', 'Concrete034', 'RoofingTiles003',
  'RoofingTiles013A', 'Grass005', 'PavingStones138', 'Asphalt033'];
const root = path.join(__dirname, '..');
let out = '// GENERATED by tools/cc0pack.js from the ambientCG CC0 textures listed in\n' +
  '// ASSETS.md (512 px JPEG, colour/normal/roughness). Do not edit by hand.\nexport const CC0 = {\n';
for (const a of ASSETS) {
  const m = (k) => 'data:image/jpeg;base64,' + fs.readFileSync(path.join(root, 'shots', `cc0_${a}_${k}.jpg`)).toString('base64');
  out += `  ${a}: { color: '${m('Color')}', normal: '${m('NormalGL')}', rough: '${m('Roughness')}' },\n`;
}
out += '};\n';
fs.writeFileSync(path.join(root, 'src', 'cc0data.js'), out);
console.log('src/cc0data.js', (out.length / 1048576).toFixed(2), 'MB');
